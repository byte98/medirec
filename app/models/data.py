"""Pydantic models used by the MediRec API."""

from __future__ import annotations

from datetime import date, datetime, time
from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field, model_validator


class HealthStatus(str, Enum):
    """Health indicator state."""

    HEALTHY = "HEALTHY"
    CAUTION = "CAUTION"
    UNHEALTHY = "UNHEALTHY"
    UNKNOWN = "UNKNOWN"


class HealthInsuranceCompany(BaseModel):
    """Health insurance company stored in the workbook."""

    abbreviation: str = Field(min_length=1)
    name: str = Field(min_length=1)
    code: str = Field(min_length=1)
    notes: str = ""


class ClientCreate(BaseModel):
    """Personal data required to create a client sheet.

    The primary identifier is generated by the storage layer and is therefore
    intentionally not accepted from the client.
    """

    surname: str = Field(min_length=1)
    name: str = Field(min_length=1)
    date_of_birth: date
    personal_id: str = Field(min_length=1)
    sex: str = Field(pattern="^[MFmf]$")
    health_insurance_abbreviation: str = Field(min_length=1)


class ClientSummary(ClientCreate):
    """Client data returned by the API."""

    identifier: str = Field(min_length=1)
    sheet_name: str


class HealthMeasurementCreate(BaseModel):
    """One health measurement."""

    date: date
    time: time
    systolic: Optional[float] = Field(default=None, ge=40, le=300)
    diastolic: Optional[float] = Field(default=None, ge=20, le=200)
    pulse: Optional[float] = Field(default=None, ge=20, le=250)
    oxygen_saturation: Optional[float] = Field(default=None, ge=50, le=100)
    height: Optional[float] = Field(default=None, gt=0, le=300)
    weight: Optional[float] = Field(default=None, ge=1, le=500)
    bmi: Optional[float] = Field(default=None, gt=0, le=200)
    notes: str = ""

    @model_validator(mode="before")
    @classmethod
    def normalize_empty_values(cls, values: object) -> object:
        """Convert empty optional form values to null values."""
        if isinstance(values, dict):
            values = {**values}
            for field in ("systolic", "diastolic", "pulse", "oxygen_saturation", "height", "weight", "bmi"):
                if values.get(field) == "":
                    values[field] = None
            if values.get("notes") is None:
                values["notes"] = ""
        reti = values
        return reti

    @model_validator(mode="after")
    def validate_pressure(self) -> "HealthMeasurementCreate":
        """Ensure systolic pressure exceeds diastolic pressure."""
        if self.systolic is not None and self.diastolic is not None and self.systolic <= self.diastolic:
            raise ValueError("Systolic pressure must exceed diastolic pressure.")
        reti = self
        return reti


class HealthMeasurement(HealthMeasurementCreate):
    """Stored health measurement with calculated indicators."""

    systolic_status: HealthStatus
    diastolic_status: HealthStatus
    pulse_status: HealthStatus
    oxygen_status: HealthStatus
    weight_status: HealthStatus
    bmi_status: HealthStatus


class ClientDetail(ClientSummary):
    """Client including health measurements."""

    measurements: list[HealthMeasurement]
